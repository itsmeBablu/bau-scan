import Foundation

/// Produces the export file for a room in a given directory (by default
/// a dedicated temporary directory) and returns its URL, ready for `ShareLink`,
/// `fileExporter`, Mac drag-and-drop, or copying into `Exports/`.
/// 2D and JSON are generated; USDZ copied from package; OBJ/STL/PLY built from
/// the plan (`PlanMeshBuilder`) or converted from scan mesh (`ModelIOConverter`).
struct ExportService {
    var locale: Locale = AppLanguage.locale
    var unit: MeasurementUnit = MeasurementUnit(rawValue: UserDefaults.standard.string(forKey: "measurementUnit") ?? "") ?? .both
    var pageSize = CGSize(width: 842, height: 595)  // A4 paysage, points
    var pngPixelScale: CGFloat = 3
    var includePDFPhotos = UserDefaults.standard.object(forKey: PDFPhotoPolicy.preferenceKey) as? Bool ?? PDFPhotoPolicy.defaultValue

    enum ExportError: LocalizedError {
        case notAvailable(ExportFormat)
        case missingSource(String)
        var errorDescription: String? {
            switch self {
            case .notAvailable(let f): String(localized:"export.error.notAvailable \(String(localized: String.LocalizationValue(f.titleKey)))",locale:AppLanguage.locale)
            case .missingSource(let n): String(localized:"export.error.missingSource \(n)",locale:AppLanguage.locale)
            }
        }
    }

    /// Source of OBJ / STL / PLY meshes.
    enum MeshSource: String, CaseIterable, Identifiable {
        /// Parametric mesh built from plan (`PlanMeshBuilder`): clean, lightweight, identical on iOS/Mac.
        case parametric
        /// Raw scan mesh (`room-mesh.usdz`) converted by Model I/O: detailed, heavier, iPhone only at capture.
        case scan
        var id: String { rawValue }
        var titleKey: String { "export.meshSource.\(rawValue)" }
    }
    var meshSource: MeshSource = .parametric

    /// Available export formats: USDZ formats only appear if file exists
    /// (raw mesh is only generated by iPhone LiDAR scans); ZIP bundles all formats.
    static func availableFormats(packageURL: URL?) -> [ExportFormat] {
        availableFormats(usdzURL: packageURL.flatMap { RoomPackage.usdzURL(in: $0) }, usdzMeshURL: packageURL.flatMap { RoomPackage.usdzMeshURL(in: $0) })
    }

    static func availableFormats(for subject: ExportSubject) -> [ExportFormat] {
        var formats = availableFormats(usdzURL:subject.usdzURL,usdzMeshURL:subject.usdzMeshURL)
        if DeferredCaptureExport.hasSource(subject.sourcePackageURL) {
            if !formats.contains(.usdzParametric) { formats.insert(.usdzParametric,at:4) }
            if subject.kind == .room,!formats.contains(.usdzMesh) { formats.insert(.usdzMesh,at:5) }
        }
        return formats
    }

    static func availableFormats(usdzURL: URL?, usdzMeshURL: URL?) -> [ExportFormat] {
        var formats: [ExportFormat] = [.pdf, .png, .svg, .dxf]
        if usdzURL != nil { formats.append(.usdzParametric) }
        if usdzMeshURL != nil { formats.append(.usdzMesh) }
        formats += [.obj, .stl, .ply, .json, .zip]
        return formats
    }

    /// Does the package contain raw scan mesh?
    static func hasScanMesh(packageURL: URL?) -> Bool { packageURL.flatMap { RoomPackage.usdzMeshURL(in: $0) } != nil }

    /// Sanitized filename (without path separators or illegal characters).
    static func fileName(for record: RoomRecord, format: ExportFormat) -> String {
        folderName(for: record) + format.fileSuffix + "." + format.fileExtension
    }

    static func fileName(for subject: ExportSubject, format: ExportFormat) -> String {
        if LevelExportService.needsArchive(house:subject.house,format:format) { return folderName(for:subject)+"-"+format.rawValue+"-levels.zip" }
        return folderName(for: subject) + format.fileSuffix + "." + format.fileExtension
    }

    /// Subdirectory name `Exports/<Room>/` (same sanitization). A name reduced to dots
    /// (`.`, `..`) or empty becomes `room` to prevent directory traversal.
    static func folderName(for record: RoomRecord) -> String { folderName(record.name, fallback: "room") }

    static func folderName(for subject: ExportSubject) -> String {
        folderName(subject.name, fallback: subject.kind == .house ? "house" : "room")
    }

    static func folderName(_ name: String, fallback: String) -> String {
        var base = name.trimmingCharacters(in: .whitespacesAndNewlines)
        let forbidden = CharacterSet(charactersIn: "/\\:*?\"<>|\n\r\t")
        base = String(base.unicodeScalars.map { forbidden.contains($0) ? "-" : Character($0) })
        if base.isEmpty || base.allSatisfy({ $0 == "." }) { return fallback }
        return ArchivePath.component(base,fallback:fallback)
    }

    static let scratchRoot = FileManager.default.temporaryDirectory.appendingPathComponent("RoomScannerExports", isDirectory: true)

    /// Unique temporary subdirectory per export: multiple exports can run concurrently
    /// (export sheet, drag-and-drop) without colliding. Subdirectories older
    /// than one hour are cleaned up automatically.
    static func scratchDirectory() throws -> URL {
        let fm = FileManager.default
        try fm.createDirectory(at: scratchRoot, withIntermediateDirectories: true)
        let cutoff = Date().addingTimeInterval(-3600)
        for old in (try? fm.contentsOfDirectory(at: scratchRoot, includingPropertiesForKeys: [.contentModificationDateKey])) ?? [] {
            if let d = (try? old.resourceValues(forKeys: [.contentModificationDateKey]))?.contentModificationDate, d < cutoff { try? fm.removeItem(at: old) }
        }
        let url = scratchRoot.appendingPathComponent(UUID().uuidString, isDirectory: true)
        try fm.createDirectory(at: url, withIntermediateDirectories: true)
        return url
    }

    /// Content of generated export (2D + JSON). Formats copied from package
    /// (USDZ) go through `export(_:record:format:packageURL:to:)`.
    func data(for house: House, format: ExportFormat, title: String) throws -> Data {
        var renderer = PlanRenderer()
        renderer.options.locale = locale
        renderer.options.unit = unit
        switch format {
        case .pdf: return renderer.pdfData(house, size: pageSize, title: title)
        case .png:
            guard let d = renderer.pngData(house, pageSize: pageSize, pixelScale: pngPixelScale) else { throw ExportError.missingSource("png") }
            return d
        case .svg: return SVGExporter(locale: locale, unit: unit).data(for: house)
        case .dxf: return DXFExporter(locale: locale, unit: unit).data(for: house)
        case .json:
            // Single room remains `FloorPlan` (v1 compatibility); house is encoded in full.
            if house.stories.count == 1, house.stories[0].rooms.count == 1 { return try RoomPackage.encoder.encode(house.stories[0].rooms[0]) }
            return try RoomPackage.encoder.encode(house)
        case .obj: return MeshWriters.obj(PlanMeshBuilder().build(house), name: title)
        case .stl: return MeshWriters.stl(PlanMeshBuilder().build(house), name: title)
        case .ply: return MeshWriters.ply(PlanMeshBuilder().build(house), name: title)
        default: throw ExportError.notAvailable(format)
        }
    }

    /// Temporary folder containing all exports + README.txt, then compressed into ZIP.
    private func archive(_ subject: ExportSubject, to dest: URL) throws {
        let staging = FileManager.default.temporaryDirectory.appendingPathComponent("RoomScannerArchive-\(UUID().uuidString)", isDirectory: true)
        let folder = staging.appendingPathComponent(Self.folderName(for: subject), isDirectory: true)
        try FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: staging) }
        var files: [(name: String, format: ExportFormat)] = []
        let geometryFolder = folder.appendingPathComponent("Data",isDirectory:true)
        try FileManager.default.createDirectory(at:geometryFolder,withIntermediateDirectories:true)
        try ResolvedGeometryExporter.data(for:subject.house,sourceID:subject.id).write(to:geometryFolder.appendingPathComponent("resolved-geometry.json"))
        files.append(("Data/resolved-geometry.json",.json))
        for format in Self.availableFormats(for: subject) where format != .zip {
            let category = format.group == .twoD ? "Plans" : format.group == .threeD ? "Models" : "Data"
            let url = try export(subject, format: format, to: folder.appendingPathComponent(category,isDirectory:true))
            files.append((category+"/"+url.lastPathComponent, format))
        }
        if let package = subject.sourcePackageURL {
            var used = PhotoArchiveLayout()
            let photos = try SurveyPhotoArchiveWriter.write(SurveyPhotoStore.images(from:package,house:subject.house),to:folder,used:&used,sourceID:subject.id.uuidString)
            let encoder = JSONEncoder(); encoder.outputFormatting = [.prettyPrinted,.sortedKeys]
            try encoder.encode(photos).write(to:folder.appendingPathComponent("photo-index.json"))
        }
        try ArchiveExporter.readme(subject: subject, files: files, locale: locale).write(to: folder.appendingPathComponent("README.txt"), atomically: true, encoding: .utf8)
        try ArchiveExporter.zip(directory: folder, to: dest)
    }

    private func copy(_ src: URL?, missing: String, to dest: URL) throws {
        guard let src, FileManager.default.fileExists(atPath: src.path) else { throw ExportError.missingSource(missing) }
        try FileManager.default.copyItem(at: src, to: dest)
    }

    /// Room export (`RoomRecord` + `.roomscan` package), v1 structure retained.
    @discardableResult
    func export(_ house: House, record: RoomRecord, format: ExportFormat, packageURL: URL?, to directory: URL? = nil) throws -> URL {
        try export(ExportSubject(record: record, house: house, packageURL: packageURL), format: format, to: directory)
    }

    /// Export of a subject (room or house) into `directory` (or unique temporary folder).
    @discardableResult
    func export(_ subject: ExportSubject, format: ExportFormat, to directory: URL? = nil) throws -> URL {
        let dir = try directory ?? Self.scratchDirectory()
        try FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        let dest = dir.appendingPathComponent(Self.fileName(for: subject, format: format))
        try? FileManager.default.removeItem(at: dest)
        if LevelExportService.needsArchive(house:subject.house,format:format), meshSource == .parametric || ![ExportFormat.obj,.stl,.ply].contains(format) {
            let scans = try subject.sourcePackageURL.flatMap { try HousePackage.readStructure(from:$0)?.rooms } ?? []
            try LevelExportService.write(house:subject.house,scans:scans,format:format,locale:locale,unit:unit,to:dest)
            return dest
        }
        switch format {
        case .usdzParametric: try copy(DeferredCaptureExport.url(subject,mesh:false), missing: FileLayout.PackageFile.usdz, to: dest)
        case .usdzMesh: try copy(DeferredCaptureExport.url(subject,mesh:true), missing: FileLayout.PackageFile.usdzMesh, to: dest)
        case .obj where meshSource == .scan, .stl where meshSource == .scan, .ply where meshSource == .scan:
            guard let src = try DeferredCaptureExport.url(subject,mesh:true) else { throw ExportError.missingSource(FileLayout.PackageFile.usdzMesh) }
            try ModelIOConverter.convert(src, to: dest)
        case .pdf:
            let plan = try data(for: subject.house, format: .pdf, title: subject.name)
            let sources = includePDFPhotos ? try subject.sourcePackageURL.map { try SurveyPhotoExportSource.list(from:$0,house:subject.house) } ?? [] : []
            try PDFPhotoAppendix.append(to:plan,sources:sources,locale:locale).write(to:dest,options:.atomic)
        case .png, .svg, .dxf, .json, .obj, .stl, .ply:
            try data(for: subject.house, format: format, title: subject.name).write(to: dest, options: .atomic)
        case .zip:
            try archive(subject, to: dest)
        }
        return dest
    }
}
